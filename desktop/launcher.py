if not getattr(sys, 'frozen', False):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'backend' / 'calendar_api'))


def bundled_root():
    return Path(sys._MEIPASS) if getattr(sys, 'frozen', False) else Path(__file__).resolve().parents[1] / '.build' / 'desktop'


def prepare_database(data_dir):
    data_dir.mkdir(parents=True, exist_ok=True)
    database = data_dir / 'calendar.db'
    if not database.exists():
        # Copy only the seed generated by the build; never bundle a developer's DB.
        with (bundled_root() / 'seed.db').open('rb') as source, database.open('xb') as target:
            shutil.copyfileobj(source, target)
    os.environ['CALENDAR_DB'] = str(database)
    os.environ['CALENDAR_DEMO_AUTH'] = '1'
    return database


def make_app(data_dir):
    prepare_database(data_dir)
    from main import app
    from fastapi import HTTPException
    from fastapi.responses import FileResponse, RedirectResponse
    from fastapi.staticfiles import StaticFiles
    from starlette.middleware.trustedhost import TrustedHostMiddleware
    web = bundled_root() / 'web'
    if not (web / 'index.html').is_file():
        raise RuntimeError('웹페이지 파일을 찾을 수 없습니다.')
    app.add_middleware(TrustedHostMiddleware, allowed_hosts=['127.0.0.1', 'localhost'])
    app.mount('/assets', StaticFiles(directory=web / 'assets'), name='desktop-assets')

    @app.get('/', include_in_schema=False)
    def home():
        return RedirectResponse('/w/cafe/calendar?date=2026-09-09')

    @app.get('/{page:path}', include_in_schema=False)
    def spa(page: str):
        if page == 'api' or page.startswith(('api/', 'assets/')):
            raise HTTPException(404)
        return FileResponse(web / 'index.html', headers={'Cache-Control': 'no-cache'})

    return app


class PreviewServer:
    def __init__(self, data_dir, port=0):
        self.data_dir = data_dir
        self.port = port
        self.server = None
        self.thread = None
        self.error = None
        self.socket = None
        self.stopping = threading.Event()

    def start(self):
        self.thread = threading.Thread(target=self._run, daemon=True)
        self.thread.start()

    def _run(self):
        try:
            import uvicorn
            app = make_app(self.data_dir)
            self.socket = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            if hasattr(socket, 'SO_EXCLUSIVEADDRUSE'):
                self.socket.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
            self.socket.bind(('127.0.0.1', self.port))
            self.port = self.socket.getsockname()[1]
            config = uvicorn.Config(app, host='127.0.0.1', port=self.port,
                                    log_config=None, access_log=False, loop='asyncio',
                                    http='h11', ws='none', lifespan='on')
            self.server = uvicorn.Server(config)
            if not self.stopping.is_set():
                self.server.run(sockets=[self.socket])
        except Exception as error:
            self.error = error
            logging.exception('Could not start ShiftLink')
        finally:
            if self.socket:
                self.socket.close()

    @property
    def ready(self):
        return self.server is not None and self.server.started and self.thread.is_alive()

    @property
    def url(self):
        return f'http://127.0.0.1:{self.port}/w/cafe/calendar?date=2026-09-09'

    def stop(self):
        self.stopping.set()
        if self.server:
            self.server.should_exit = True
        if self.thread:
            self.thread.join(timeout=8)


def self_test(server, report_path):
    """Exercise the frozen binary without relying on Node/Python installed on PATH."""
    report = {'ok': False}
    try:
        import tkinter
        tcl_version = tkinter.Tcl().eval('info patchlevel')
        deadline = time.monotonic() + 45
        while not server.ready:
            if server.error:
                raise server.error
            if time.monotonic() > deadline:
                raise TimeoutError('Server startup timeout')
            time.sleep(0.1)
        def get(path):
            connection = http.client.HTTPConnection('127.0.0.1', server.port, timeout=10)
            try:
                connection.request('GET', path, headers={'X-User-Id': '2', 'X-Workspace-Id': 'cafe'})
                response = connection.getresponse()
                assert response.status == 200, (path, response.status)
                return response.read()
            finally:
                connection.close()

        assert json.loads(get('/api/health'))['status'] == 'ok'
        month = json.loads(get('/api/calendar?year=2026&month=9'))
        assert any(day['has_event'] for day in month['days'])
        import re
        html = get('/w/cafe/payroll/history').decode()
        script = re.search(r'<script[^>]+src="([^"]+)"', html).group(1)
        assert len(get(script)) > 1000
        assert len(get('/assets/NotoSansKR.ttf')) > 1000
        assert len(get('/assets/figma/payroll-chevron.svg')) > 0
        from main import connect
        with connect() as conn:
            conn.execute('CREATE TABLE IF NOT EXISTS desktop_self_test (runs INTEGER NOT NULL)')
            previous = conn.execute('SELECT runs FROM desktop_self_test').fetchone()
            runs = previous[0] + 1 if previous else 1
            conn.execute('DELETE FROM desktop_self_test')
            conn.execute('INSERT INTO desktop_self_test VALUES (?)', (runs,))
        report = {'ok': True, 'url': server.url, 'calendarDays': len(month['days']),
                  'persistentRuns': runs, 'frozen': bool(getattr(sys, 'frozen', False)), 'tcl': tcl_version}
    except Exception:
        report['error'] = traceback.format_exc()
    finally:
        server.stop()
        report['stopped'] = not server.thread.is_alive()
        report['ok'] = report['ok'] and report['stopped']
        report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    return 0 if report['ok'] else 1


def show_window(server, open_browser):
    import tkinter as tk
    root = tk.Tk()
    root.title('시프트링크')
    root.geometry('380x240')
    root.resizable(False, False)
    root.configure(bg='#f9f9f9')
    root.option_add('*Font', ('맑은 고딕', 10))
    tk.Label(root, text='시프트링크', bg='#f9f9f9', fg='#17658f',
             font=('맑은 고딕', 20, 'bold')).pack(pady=(25, 8))
    status = tk.StringVar(value='웹페이지를 준비하고 있어요…')
    tk.Label(root, textvariable=status, bg='#f9f9f9', fg='#666f7d', wraplength=330).pack()
    open_button = tk.Button(root, text='웹페이지 다시 열기', state='disabled',
                            command=lambda: webbrowser.open(server.url), relief='flat',
                            bg='#51b7f9', fg='#202631', padx=30, pady=9)
    open_button.pack(pady=(18, 8))

    def close():
        status.set('종료하고 있어요…')
        root.update_idletasks()
        server.stop()
        root.destroy()

    def poll():
        if server.error:
            status.set('실행하지 못했어요. 창을 닫고 다시 실행해 주세요.')
        elif server.ready:
            status.set('실행 중 · 아래 버튼으로 화면을 다시 열 수 있어요.')
            open_button.configure(state='normal')
            if open_browser:
                webbrowser.open(server.url)
        else:
            root.after(150, poll)

    tk.Button(root, text='종료', command=close, relief='flat', bg='#f9f9f9', fg='#666f7d').pack()
    root.protocol('WM_DELETE_WINDOW', close)
    root.after(100, poll)
    root.mainloop()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--data-dir', type=Path)
    parser.add_argument('--port', type=int, default=0)
    parser.add_argument('--no-browser', action='store_true')
    parser.add_argument('--self-test', action='store_true')
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    if args.self_test and (not args.data_dir or not args.report):
        parser.error('--self-test requires isolated --data-dir and --report')
    data_dir = args.data_dir or Path(os.environ.get('LOCALAPPDATA', str(Path.home()))) / 'ShiftLinkPreview'
    data_dir.mkdir(parents=True, exist_ok=True)
    logging.basicConfig(filename=data_dir / 'preview.log', encoding='utf-8', level=logging.INFO)
    server = PreviewServer(data_dir, args.port)
    server.start()
    if args.self_test:
        return self_test(server, args.report)
    try:
        show_window(server, not args.no_browser)
    finally:
        server.stop()
    return 0


if __name__ == '__main__':
    sys.exit(main())
